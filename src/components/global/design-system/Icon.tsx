export type IconName = (typeof ICON_NAMES)[number];

/**
 * Inline icon from the vendored sprite (public/icons.svg, generated by
 * scripts/vendor-assets.mjs from ICON_NAMES - a few dozen symbols
 * instead of the 1,357-SVG web-component set).
 *
 * `label` makes the icon an accessible image; without one it is
 * decoration and hidden from assistive tech.
 */
export default function Icon({
	name,
	className,
	label,
	ariaHidden
}: {
	name: IconName;
	className?: string;
	/** accessible name; presence implies role="img" */
	label?: string;
	/** force aria-hidden (defaults to hidden when no label) */
	ariaHidden?: boolean;
}) {
	return (
		<svg
			className={cn("inline-block", className)}
			viewBox="0 0 512 512"
			role={label ? "img" : undefined}
			aria-label={label}
			aria-hidden={ariaHidden ?? (label ? undefined : true)}
			fill="currentColor"
		>
			<use href={`/icons.svg#${name}`} />
		</svg>
	);
}
